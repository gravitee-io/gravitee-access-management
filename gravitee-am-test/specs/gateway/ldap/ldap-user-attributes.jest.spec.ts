import { afterAll, beforeAll, beforeEach, describe, expect, it } from '@jest/globals';
import { login, getHeaderLocation } from '@gateway-commands/login-commands';
import { performGet, logoutUser } from '@gateway-commands/oauth-oidc-commands';
import { deleteUser, listUsers } from '@management-commands/user-management-commands';
import { setup, retryImmediatelyForThisFile } from '../../test-fixture';
import { jira } from '@specs-utils/jira';
import { LdapFixture, setupLdapFixture, LDAP_ADMIN, REDIRECT_URI } from './fixtures/ldap-fixture';

setup(200000);

/**
 * Each test re-applies its own mappers and beforeEach drops the user, so a deferred
 * retry would still be correct here. Retrying in place anyway keeps every spec in
 * this folder consistent, and absorbs the window where the gateway has reported the
 * domain synced but has not yet rebuilt the identity provider.
 */
retryImmediatelyForThisFile();

let fixture: LdapFixture;

/**
 * Operational attributes are generated by the directory rather than stored on the
 * entry, so they are only returned when explicitly requested — either by name or
 * via the '+' wildcard.
 *
 * Surfacing one in the AM user profile takes BOTH stages:
 *   1. userReturnAttribute must cause it to be FETCHED from LDAP
 *   2. a user mapper must MAP it into the profile
 * Either stage alone leaves the profile without it.
 */
const CREATE_TIMESTAMP = 'createTimestamp';
const ENTRY_UUID = 'entryUUID';

beforeAll(async () => {
  fixture = await setupLdapFixture();
});

afterAll(async () => {
  if (fixture) {
    await fixture.cleanUp();
  }
});

/**
 * Profile attributes are merged, never replaced, so anything a previous test wrote
 * would still be present and make an "attribute is absent" assertion pass or fail
 * for the wrong reason. Dropping the AM user forces it to be re-provisioned from
 * the directory on the next login, giving every test a clean profile. The LDAP
 * entry itself is untouched.
 */
beforeEach(async () => {
  const page = await listUsers(fixture.domain.id, fixture.accessToken, LDAP_ADMIN.username);
  if (page.totalCount > 0) {
    await deleteUser(fixture.domain.id, fixture.accessToken, page.data[0].id);
  }
});

async function authenticateAndReadProfile(): Promise<Record<string, unknown>> {
  const clientId = fixture.app.settings.oauth.clientId;
  const authResponse = await performGet(
    fixture.openIdConfiguration.authorization_endpoint,
    `?response_type=code&client_id=${clientId}&redirect_uri=${REDIRECT_URI}&scope=openid`,
  ).expect(302);

  const postLogin = await login(authResponse, LDAP_ADMIN.username, clientId, LDAP_ADMIN.password);
  const loginResponse = await getHeaderLocation(postLogin);
  expect(loginResponse.headers['location']).toContain(`${REDIRECT_URI}?code=`);
  await logoutUser(fixture.openIdConfiguration.end_session_endpoint, loginResponse);

  const page = await listUsers(fixture.domain.id, fixture.accessToken, LDAP_ADMIN.username);
  expect(page.totalCount).toBeGreaterThan(0);
  return page.data[0].additionalInformation ?? {};
}

describe('LDAP user attributes - no return attribute configured', () => {
  it(jira`should surface no operational attributes when the return attribute is empty ${'AM-4295'}`, async () => {
    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: '' });

    const profile = await authenticateAndReadProfile();

    // Nothing is requested from the directory, so the mapper has nothing to map.
    expect(profile[CREATE_TIMESTAMP]).toBeUndefined();
    expect(profile[ENTRY_UUID]).toBeUndefined();
  });
});

describe("LDAP user attributes - '+' return attribute", () => {
  it(jira`should NOT surface operational attributes when no user mapper maps them ${'AM-4298'}`, async () => {
    await fixture.setUserMappers({}, { userReturnAttribute: '+' });

    const profile = await authenticateAndReadProfile();

    expect(profile[CREATE_TIMESTAMP]).toBeUndefined();
    expect(profile[ENTRY_UUID]).toBeUndefined();
  });

  it(jira`should surface an operational attribute once a user mapper maps it ${'AM-4299'}`, async () => {
    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: '+' });

    const profile = await authenticateAndReadProfile();

    // OpenLDAP generalized time, e.g. 20260811142049Z
    expect(profile[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);
  });
});

describe('LDAP user attributes - named return attribute', () => {
  it(jira`should NOT surface a named operational attribute without a user mapper ${'AM-4296'}`, async () => {
    await fixture.setUserMappers({}, { userReturnAttribute: ENTRY_UUID });

    const profile = await authenticateAndReadProfile();

    expect(profile[ENTRY_UUID]).toBeUndefined();
  });

  it(jira`should surface a named operational attribute when it is also mapped ${'AM-4297'}`, async () => {
    await fixture.setUserMappers({ [ENTRY_UUID]: ENTRY_UUID }, { userReturnAttribute: ENTRY_UUID });

    const profile = await authenticateAndReadProfile();

    expect(profile[ENTRY_UUID]).toMatch(/^[0-9a-f-]{36}$/);
  });

  it(jira`should NOT surface an attribute that is mapped but never fetched ${'AM-7447'}`, async () => {
    // entryUUID is requested, createTimestamp is not — mapping alone cannot
    // conjure an attribute the directory was never asked for.
    await fixture.setUserMappers(
      { [ENTRY_UUID]: ENTRY_UUID, [CREATE_TIMESTAMP]: CREATE_TIMESTAMP },
      { userReturnAttribute: ENTRY_UUID },
    );

    const profile = await authenticateAndReadProfile();

    expect(profile[ENTRY_UUID]).toMatch(/^[0-9a-f-]{36}$/);
    expect(profile[CREATE_TIMESTAMP]).toBeUndefined();
  });
});

describe('LDAP user attributes - multiple return attributes', () => {
  it(jira`should fetch every attribute in a comma-separated return attribute list ${'AM-7447'}`, async () => {
    // The plugin splits this field on ',' and trims each entry, so several
    // operational attributes can be requested at once. The surrounding spaces are
    // deliberate — they exercise the trim.
    await fixture.setUserMappers(
      { [CREATE_TIMESTAMP]: CREATE_TIMESTAMP, [ENTRY_UUID]: ENTRY_UUID },
      { userReturnAttribute: `${ENTRY_UUID} , ${CREATE_TIMESTAMP}` },
    );

    const profile = await authenticateAndReadProfile();

    expect(profile[ENTRY_UUID]).toMatch(/^[0-9a-f-]{36}$/);
    expect(profile[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);
  });
});

describe('LDAP user attributes - adding a mapper to an existing user', () => {
  it(jira`should surface a newly mapped attribute on the next login with '+' ${'AM-4302'}`, async () => {
    await fixture.setUserMappers({}, { userReturnAttribute: '+' });
    const before = await authenticateAndReadProfile();
    expect(before[CREATE_TIMESTAMP]).toBeUndefined();

    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: '+' });
    const after = await authenticateAndReadProfile();

    expect(after[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);
  });

  it(jira`should surface a different attribute after the return attribute is switched ${'AM-4303'}`, async () => {
    // Start with one operational attribute fetched and mapped...
    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: CREATE_TIMESTAMP });
    const before = await authenticateAndReadProfile();
    expect(before[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);
    expect(before[ENTRY_UUID]).toBeUndefined();

    // ...then switch BOTH the return attribute and the mapper to a different one.
    await fixture.setUserMappers({ [ENTRY_UUID]: ENTRY_UUID }, { userReturnAttribute: ENTRY_UUID });
    const after = await authenticateAndReadProfile();

    expect(after[ENTRY_UUID]).toMatch(/^[0-9a-f-]{36}$/);
  });
});

describe('LDAP user attributes - removing a mapper', () => {
  it(jira`should keep an already-stored attribute after its mapper is removed ${'AM-4305'}`, async () => {
    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: '+' });
    const before = await authenticateAndReadProfile();
    expect(before[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);

    // Profile updates merge rather than replace, so a value already written to the
    // user survives the mapper being taken away.
    await fixture.setUserMappers({}, { userReturnAttribute: '+' });
    const after = await authenticateAndReadProfile();

    expect(after[CREATE_TIMESTAMP]).toEqual(before[CREATE_TIMESTAMP]);
  });

  it(jira`should keep an already-stored attribute after both mapper and return attribute are cleared ${'AM-4306'}`, async () => {
    await fixture.setUserMappers({ [CREATE_TIMESTAMP]: CREATE_TIMESTAMP }, { userReturnAttribute: '+' });
    const before = await authenticateAndReadProfile();
    expect(before[CREATE_TIMESTAMP]).toMatch(/^\d{14}Z$/);

    // Clearing the return attribute as well as the mapper stops the attribute
    // being fetched at all, yet the value already written to the profile remains.
    await fixture.setUserMappers({}, { userReturnAttribute: '' });
    const after = await authenticateAndReadProfile();

    expect(after[CREATE_TIMESTAMP]).toEqual(before[CREATE_TIMESTAMP]);
  });
});
