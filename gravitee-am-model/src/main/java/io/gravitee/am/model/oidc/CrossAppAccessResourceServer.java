package io.gravitee.am.model.oidc;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * A protected resource an authority exposes, and which AM may mint an ID-JAG towards.
 *
 * <p>The {@code id} is generated by AM and never changes, so an application referencing this resource
 * server survives a rename or a move to another audience.
 *
 * @author GraviteeSource Team
 */
@Data
@Builder(toBuilder = true)
@NoArgsConstructor
@AllArgsConstructor
@Schema(title = "Cross App Access resource server",
        description = "A resource server AM may mint an ID-JAG towards, behind this authority's authorization server.")
public class CrossAppAccessResourceServer {

    public static final int NAME_MAX_LENGTH = 255;

    public static final int RESOURCE_MAX_LENGTH = 512;

    @Schema(description = "Identifier generated by AM. Echo it back on update to keep this resource "
            + "server's identity across a rename or a new resource; anything else is given a new one.")
    private String id;

    @Schema(description = "Label the resource server is known by.",
            example = "Acme Calendar", maxLength = NAME_MAX_LENGTH)
    private String name;

    @Schema(description = "Resource identifier of the resource server, as defined by RFC 8707. Carried "
            + "by the \"resource\" claim of the ID-JAG. An absolute URI, unique within this authority.",
            example = "https://calendar.acme.com", maxLength = RESOURCE_MAX_LENGTH)
    private String resource;

    public CrossAppAccessResourceServer(CrossAppAccessResourceServer other) {
        this.id = other.id;
        this.name = other.name;
        this.resource = other.resource;
    }
}
