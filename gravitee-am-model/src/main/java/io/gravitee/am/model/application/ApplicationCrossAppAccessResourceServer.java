package io.gravitee.am.model.application;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * A resource server this application may reach, and the identity it holds there.
 *
 * <p>The resource server is defined on a trusted domain of the security domain. A row whose resource
 * server no longer exists is kept as-is: it is reported as unresolved by the Console and ignored when
 * minting, rather than blocking every later update of the application.
 *
 * @author GraviteeSource Team
 */
@Data
@Builder(toBuilder = true)
@NoArgsConstructor
@AllArgsConstructor
@Schema(title = "Cross App Access resource server mapping",
        description = "A resource server this application may request an ID-JAG for.")
public class ApplicationCrossAppAccessResourceServer {

    public static final int CLIENT_ID_MAX_LENGTH = 512;

    @Schema(description = "Identifier of the trusted domain the resource server belongs to. A hint used to "
            + "resolve the resource server; the resource server identifier remains authoritative.")
    private String trustDomainId;

    @Schema(description = "Identifier of the resource server, as generated by AM on the trusted domain.")
    private String resourceServerId;

    @Schema(description = "Identifier this application is registered with at the resource authorization server.",
            example = "acme-calendar-client", maxLength = CLIENT_ID_MAX_LENGTH)
    private String clientId;

    public ApplicationCrossAppAccessResourceServer(ApplicationCrossAppAccessResourceServer other) {
        this.trustDomainId = other.trustDomainId;
        this.resourceServerId = other.resourceServerId;
        this.clientId = other.clientId;
    }
}
